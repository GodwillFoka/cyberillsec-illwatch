/**
 * Table de libellés traduite à la lecture : `INCIDENT_STATUS[code]` rend le libellé dans la
 * langue courante (undefined pour un code inconnu, comme un objet ordinaire).
 */
export function labelTable(prefix: string, codes: readonly string[]): Readonly<Record<string, string>> {
  const known = new Set(codes);
  return new Proxy({} as Record<string, string>, {
    get: (_target, key) =>
      typeof key === "string" && known.has(key) ? labels(`${prefix}.${key}` as Parameters<typeof labels>[0]) : undefined,
    has: (_target, key) => typeof key === "string" && known.has(key),
    ownKeys: () => [...known],
    getOwnPropertyDescriptor: (_target, key) =>
      typeof key === "string" && known.has(key)
        ? { enumerable: true, configurable: true, value: labels(`${prefix}.${key}` as Parameters<typeof labels>[0]) }
        : undefined,
  });
}
