COST = tuple(tuple(int(x) for x in row.split()) for row in _TABLE.strip().splitlines())
_LETTERS = re.compile(r"[a-z]+")


def bigram_cost(label: str) -> float:
    """Coût moyen d'une transition (bits) sur les suites de lettres du libellé ; 0 sans lettre."""
    total = count = 0
    for run in _LETTERS.findall(label.lower()):
        padded = f"^{run}^"
        for a, b in zip(padded, padded[1:], strict=False):
            total += COST[_INDEX[a]][_INDEX[b]]
            count += 1
    return total / count / 10 if count else 0.0
